-- RiskLens initial PostgreSQL schema
-- Flyway migration: V1

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_email_not_blank CHECK (length(trim(email)) > 0),
    CONSTRAINT chk_users_password_hash_not_blank CHECK (length(trim(password_hash)) > 0),
    CONSTRAINT chk_users_role_not_blank CHECK (length(trim(role)) > 0)
);

CREATE TABLE portfolios (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL,
    name VARCHAR(100) NOT NULL,
    base_currency VARCHAR(3) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_portfolios_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT chk_portfolios_name_not_blank CHECK (length(trim(name)) > 0),
    CONSTRAINT chk_portfolios_base_currency CHECK (base_currency ~ '^[A-Z]{3}$')
);

CREATE INDEX ix_portfolios_user_id ON portfolios (user_id);

CREATE TABLE positions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    portfolio_id UUID NOT NULL,
    asset_symbol VARCHAR(20) NOT NULL,
    asset_type VARCHAR(10) NOT NULL,
    quantity NUMERIC(24, 8) NOT NULL,
    avg_buy_price NUMERIC(24, 8) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_positions_portfolio_asset UNIQUE (portfolio_id, asset_symbol),
    CONSTRAINT fk_positions_portfolio
        FOREIGN KEY (portfolio_id) REFERENCES portfolios (id) ON DELETE CASCADE,
    CONSTRAINT chk_positions_symbol_not_blank CHECK (length(trim(asset_symbol)) > 0),
    CONSTRAINT chk_positions_type_not_blank CHECK (length(trim(asset_type)) > 0),
    CONSTRAINT chk_positions_quantity_non_negative CHECK (quantity >= 0),
    CONSTRAINT chk_positions_avg_buy_price_non_negative CHECK (avg_buy_price >= 0)
);

CREATE INDEX ix_positions_portfolio_id ON positions (portfolio_id);
CREATE INDEX ix_positions_asset_symbol ON positions (asset_symbol);

CREATE TABLE price_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_symbol VARCHAR(20) NOT NULL,
    asset_type VARCHAR(10) NOT NULL,
    price_date DATE NOT NULL,
    close_price NUMERIC(24, 8) NOT NULL,
    source VARCHAR(30),
    CONSTRAINT uq_price_history_asset_date UNIQUE (asset_symbol, asset_type, price_date),
    CONSTRAINT chk_price_history_symbol_not_blank CHECK (length(trim(asset_symbol)) > 0),
    CONSTRAINT chk_price_history_type_not_blank CHECK (length(trim(asset_type)) > 0),
    CONSTRAINT chk_price_history_close_price_non_negative CHECK (close_price >= 0)
);

CREATE INDEX ix_price_history_asset_date
    ON price_history (asset_symbol, asset_type, price_date DESC);

CREATE TABLE risk_assessments (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    portfolio_id UUID NOT NULL,
    calculated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    volatility NUMERIC(12, 6) NOT NULL,
    var_95 NUMERIC(12, 6) NOT NULL,
    max_drawdown NUMERIC(12, 6) NOT NULL,
    sharpe_ratio NUMERIC(12, 6) NOT NULL,
    risk_score SMALLINT NOT NULL,
    CONSTRAINT fk_risk_assessments_portfolio
        FOREIGN KEY (portfolio_id) REFERENCES portfolios (id) ON DELETE CASCADE,
    CONSTRAINT chk_risk_assessments_risk_score CHECK (risk_score BETWEEN 0 AND 100)
);

CREATE INDEX ix_risk_assessments_portfolio_calculated
    ON risk_assessments (portfolio_id, calculated_at DESC);

CREATE TABLE refresh_tokens (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL,
    token_hash VARCHAR(255) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_refresh_tokens_token_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT chk_refresh_tokens_token_not_blank CHECK (length(trim(token_hash)) > 0)
);

CREATE INDEX ix_refresh_tokens_user_id ON refresh_tokens (user_id);
CREATE INDEX ix_refresh_tokens_active
    ON refresh_tokens (user_id, expires_at)
    WHERE revoked_at IS NULL;

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_portfolios_updated_at
    BEFORE UPDATE ON portfolios
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_positions_updated_at
    BEFORE UPDATE ON positions
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
